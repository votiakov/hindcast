import { availPct, downtimeText, type AuditResult, type Finding } from './audit';

const pct = (n: number) => `${(n * 100).toFixed(n > 0 && n < 0.01 ? 2 : 1)}%`;
const ms = (n: number) => (n >= 1000 ? `${(n / 1000).toFixed(1)} s` : `${n} ms`);
const money = (n: number) => `${n < 0 ? '−' : ''}$${Math.abs(n).toLocaleString('en-US')}`;
const SEV = { critical: 'Critical', major: 'Major', minor: 'Minor', ok: 'OK' } as const;

function changeText(f: Finding['fixes'][number]): string {
  return f.changes
    .map((c) => {
      switch (c.op) {
        case 'set':
          return `${c.id}: ${Object.entries(c.fields)
            .map(([k, v]) => `${k} = ${typeof v === 'object' ? JSON.stringify(v) : v}`)
            .join(', ')}`;
        case 'add':
          return `add ${c.component.id} (${c.component.kind})`;
        case 'remove':
          return `remove ${c.id}`;
        case 'connect':
          return `connect ${c.from} → ${c.to}`;
        case 'disconnect':
          return `disconnect ${c.from} → ${c.to}`;
      }
    })
    .join('; ');
}

/** The audit as a Markdown document — for PRs, design docs, tickets. */
export function auditMarkdown(r: AuditResult): string {
  const L: string[] = [];
  const bad = r.findings.filter((f) => f.severity === 'critical' || f.severity === 'major');
  L.push(`# Failure audit — ${r.architecture}`);
  L.push('');
  L.push(`At **${r.load.rps.toLocaleString('en-US')} req/s** (${Math.round(r.load.readRatio * 100)}% reads), SLO: errors ≤ ${pct(r.slo.maxErrorRate)}, p99 ≤ ${ms(r.slo.maxP99Ms)}.`);
  L.push('');
  L.push('| | |');
  L.push('|---|---|');
  L.push(`| Resilience score | **${r.score}/100** — survives ${r.survived} of ${r.total} incidents within SLO |`);
  const weak = r.availability.weakest.map((w) => `${w.name} (${downtimeText(w.downtimeHoursPerYear)})`);
  L.push(`| Availability, SLA (published), not measured | ${availPct(r.availability.estimate)} — about ${downtimeText(r.availability.downtimeHoursPerYear)} of downtime a year${weak.length ? `; costs the most: ${weak.join(', ')}` : ''} |`);
  L.push(`| Headroom | ${r.headroom.ratio.toFixed(1)}× — ${Math.round(r.headroom.maxRps).toLocaleString('en-US')} req/s, then **${r.headroom.limitedBy ?? '—'}** gives out |`);
  L.push(`| Normal operation | errors ${pct(r.baseline.errorRate)}, p99 ${ms(r.baseline.p99Ms)}, ${money(r.baseline.monthly)}/month${r.baseline.meetsSlo ? '' : ' — **already outside the SLO**'} |`);
  L.push('');
  if (bad.length) {
    L.push('## What breaks first');
    L.push('');
    L.push('| severity | incident | users see | recovers | blast radius | best verified fix | $/month |');
    L.push('|---|---|---|---|---|---|---|');
    for (const f of bad) {
      const fix = f.fixes[0];
      const rec = f.impact.recoveryS === null ? '**never** (metastable)' : f.impact.selfHealS !== null && f.impact.selfHealS > 0 ? `by itself in ${f.impact.selfHealS} s` : f.impact.recoveryS === 0 ? 'when the fault clears' : `${f.impact.recoveryS} s after fix`;
      L.push(`| ${SEV[f.severity]} | ${f.title} | ${pct(f.impact.errorRate)} errors, p99 ${ms(f.impact.peakP99Ms)} | ${f.kind === 'headroom' ? '—' : rec} | ${f.blastRadius.join(', ') || '—'} | ${fix ? `${fix.title} → ${SEV[fix.after.severity].toLowerCase()}` : '—'} | ${fix ? money(fix.monthlyDelta) : ''} |`);
    }
    L.push('');
  }
  L.push('## All incidents');
  L.push('');
  for (const f of r.findings) {
    L.push(`### ${SEV[f.severity]}: ${f.title}`);
    L.push('');
    L.push(f.explanation);
    if (f.costAtRisk) L.push(`\n**${money(f.costAtRisk)} at risk** per incident.`);
    if (f.fixes.length) {
      L.push('');
      L.push('Verified fixes (re-ran the same incident):');
      L.push('');
      for (const x of f.fixes) L.push(`- **${x.title}** — ${x.why} After: ${SEV[x.after.severity].toLowerCase()}${x.after.errorRate ? `, ${pct(x.after.errorRate)} errors` : ''}. ${money(x.monthlyDelta)}/month. \`${changeText(x)}\``);
    }
    L.push('');
  }
  L.push('---');
  L.push(`Generated by Hindcast. Each incident: 10 s warm-up, fault at t = 10 s, cleared at t = 40 s, observed to t = 60 s. Results are directional — calibrate capacity, latency and price per component for real-system claims.`);
  return L.join('\n');
}
